# master/db/task_repository.py
#
# Async CRUD operations for the Task table.
# Every function receives an AsyncSession from the caller — it never creates
# its own session.  This keeps transaction control in the route handler.

from datetime import datetime
from typing import List, Optional

from sqlalchemy import select, update
from sqlalchemy.ext.asyncio import AsyncSession

from master.db.models import Task, TaskStatusDB
from shared.logger import get_logger
from shared.models import TaskRequest, TaskStatus

logger = get_logger("task_repo", node_id="master")


# ── Helper ────────────────────────────────────────────────────────────────────

def _status_to_db(status: TaskStatus) -> TaskStatusDB:
    """Convert Pydantic TaskStatus → SQLAlchemy TaskStatusDB."""
    return TaskStatusDB(status.value)


# ── Create ────────────────────────────────────────────────────────────────────

async def create_task(session: AsyncSession, task: TaskRequest) -> Task:
    """
    Persist a new task in PENDING state.

    The task_id is generated by the caller (scheduler route) so that the
    client can be told the id *before* the DB write completes.
    """
    db_task = Task(
        task_id        = task.task_id,
        image          = task.image,
        command        = task.command,
        cpu_limit      = task.cpu_limit,
        ram_limit_mb   = task.ram_limit_mb,
        priority       = task.priority,
        retry_count    = task.retry_count,
        max_retries    = task.max_retries,
        status         = TaskStatusDB.PENDING,
        created_at     = datetime.utcnow(),
    )
    session.add(db_task)
    await session.commit()
    await session.refresh(db_task)

    logger.info(
        f"Task [{task.task_id}] created — image={task.image!r}",
        extra={"event": "task_created", "task_id": task.task_id, "image": task.image},
    )
    from master.metrics import minicloud_tasks_total
    minicloud_tasks_total.labels(status="PENDING").inc()
    return db_task


# ── Read ──────────────────────────────────────────────────────────────────────

async def get_task(session: AsyncSession, task_id: str) -> Optional[Task]:
    """
    Fetch a single task by primary key. Returns None if not found.
    """
    result = await session.execute(
        select(Task).where(Task.task_id == task_id)
    )
    return result.scalar_one_or_none()


async def list_tasks(
    session: AsyncSession,
    status: Optional[TaskStatus] = None,
) -> List[Task]:
    """
    List all tasks, optionally filtered by status.
    Ordered newest-first (descending created_at).
    """
    stmt = select(Task).order_by(Task.created_at.desc())
    if status is not None:
        stmt = stmt.where(Task.status == _status_to_db(status))

    result = await session.execute(stmt)
    return list(result.scalars().all())


# ── Update ────────────────────────────────────────────────────────────────────

async def update_task_status(
    session: AsyncSession,
    task_id: str,
    **kwargs,
) -> Optional[Task]:
    """
    Partial update: only the fields passed in kwargs are written.

    Accepted kwargs:
      status               (TaskStatus)
      assigned_worker_id   (str)
      output               (str)
      error                (str)
      started_at           (datetime)
      completed_at         (datetime)
      duration_seconds     (float)

    Returns the updated Task, or None if not found.
    """
    # Convert Pydantic TaskStatus → DB enum if provided
    if "status" in kwargs and isinstance(kwargs["status"], TaskStatus):
        kwargs["status"] = _status_to_db(kwargs["status"])

    # Filter to only columns that actually exist on Task to avoid surprises
    allowed = {
        "status", "assigned_worker_id", "output", "error",
        "started_at", "completed_at", "duration_seconds",
    }
    safe_kwargs = {k: v for k, v in kwargs.items() if k in allowed}

    if not safe_kwargs:
        return await get_task(session, task_id)

    await session.execute(
        update(Task)
        .where(Task.task_id == task_id)
        .values(**safe_kwargs)
    )
    await session.commit()

    updated = await get_task(session, task_id)
    if updated:
        logger.info(
            f"Task [{task_id}] updated → status={updated.status}",
            extra={"event": "task_updated", "task_id": task_id, "status": str(updated.status)},
        )
        if "status" in safe_kwargs and updated.status:
            from master.metrics import minicloud_tasks_total, minicloud_tasks_duration_seconds
            minicloud_tasks_total.labels(status=str(updated.status.value)).inc()
            if updated.status.value in ("COMPLETED", "FAILED") and updated.duration_seconds:
                minicloud_tasks_duration_seconds.observe(updated.duration_seconds)
    return updated


# ── Cancel ────────────────────────────────────────────────────────────────────

async def cancel_task(session: AsyncSession, task_id: str) -> Optional[Task]:
    """
    Mark a task as CANCELLED.
    Only PENDING and SCHEDULED tasks can be cancelled via the DB; RUNNING tasks
    also receive a cancel signal to the worker (handled in the route layer).
    """
    task = await get_task(session, task_id)
    if task is None:
        return None

    return await update_task_status(
        session,
        task_id,
        status=TaskStatus.CANCELLED,
        completed_at=datetime.utcnow(),
    )
